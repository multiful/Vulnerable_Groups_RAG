# 3. F-18 다차원 판별 알고리즘
# ============================================================
def compute_dimensions(resp: dict) -> dict:
    return {
        "D_관계망":    resp["Q01"] + resp["Q02"] + resp["Q03"] + resp["Q04"],
        "D_활동":      resp["Q05"] + resp["Q06"],
        "D_노동경제":  resp["Q07"] + resp["Q08"],
        "D_정신건강":  resp["Q09"] + resp["Q10"] + resp["Q11"],
        "D_자기관리":  resp["Q12"],
        "B12_9":       resp["Q11"],
    }


def classify_f18(dims: dict) -> dict:
    """
    F-18 의사결정 트리
      Step 1. Safety Override  : B12_9 ≥ 2
      Step 2. 은둔청년         : D_관계망 ≥ 8 AND D_활동 ≥ 5
      Step 3. 활동제한형고립청년: D_관계망 ≥ 6
      Step 4. 활동형고립청년   : D_노동경제 ≥ 3
              else → 고립위험청년
    """
    safety = dims["B12_9"] >= 2

    if dims["D_관계망"] >= 8 and dims["D_활동"] >= 5:
        cluster = 4
        rule = "Step 2: D_관계망≥8 AND D_활동≥5"
    elif dims["D_관계망"] >= 6:
        cluster = 3
        rule = "Step 3: D_관계망≥6"
    elif dims["D_노동경제"] >= 3:
        cluster = 2
        rule = "Step 4: D_노동경제≥3"
    else:
        cluster = 1
        rule = "Step 4 else: 기타 → 고립위험"

    return {"cluster": cluster, "rule": rule, "safety": safety}


